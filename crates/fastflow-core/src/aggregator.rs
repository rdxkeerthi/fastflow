use crate::pcap::PacketRecord;
use std::collections::HashMap;
use std::net::IpAddr;

/// 5-Tuple flow identifier (Network flow key).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct FlowKey {
    pub src_ip: IpAddr,
    pub dst_ip: IpAddr,
    pub src_port: u16,
    pub dst_port: u16,
    pub protocol: u8,
}

impl FlowKey {
    /// Creates a bidirectional canonical flow key such that packets from A->B
    /// and B->A map to the same flow key.
    pub fn canonical(&self) -> Self {
        if self.src_ip < self.dst_ip
            || (self.src_ip == self.dst_ip && self.src_port <= self.dst_port)
        {
            *self
        } else {
            Self {
                src_ip: self.dst_ip,
                dst_ip: self.src_ip,
                src_port: self.dst_port,
                dst_port: self.src_port,
                protocol: self.protocol,
            }
        }
    }
}

/// Aggregated metrics for a single network flow.
#[derive(Debug, Clone, Default)]
pub struct FlowMetrics {
    pub packet_count: u64,
    pub byte_count: u64,
    pub first_seen_secs: u32,
    pub first_seen_sub: u32,
    pub last_seen_secs: u32,
    pub last_seen_sub: u32,
    pub syn_count: u32,
    pub fin_count: u32,
    pub rst_count: u32,
}

impl FlowMetrics {
    pub fn update(&mut self, record: &PacketRecord) {
        if self.packet_count == 0 {
            self.first_seen_secs = record.timestamp_secs;
            self.first_seen_sub = record.timestamp_sub;
        }
        self.last_seen_secs = record.timestamp_secs;
        self.last_seen_sub = record.timestamp_sub;

        self.packet_count += 1;
        self.byte_count += record.captured_len as u64;

        if let Some(flags) = record.tcp_flags {
            if (flags & 0x0002) != 0 {
                self.syn_count += 1;
            }
            if (flags & 0x0001) != 0 {
                self.fin_count += 1;
            }
            if (flags & 0x0004) != 0 {
                self.rst_count += 1;
            }
        }
    }

    pub fn duration_seconds(&self) -> f64 {
        let start = (self.first_seen_secs as f64) + ((self.first_seen_sub as f64) / 1_000_000.0);
        let end = (self.last_seen_secs as f64) + ((self.last_seen_sub as f64) / 1_000_000.0);
        (end - start).max(0.0)
    }
}

use std::collections::HashSet;

/// Security anomaly categories identified during traffic ingestion.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum AnomalyType {
    /// Disproportionately high TCP SYN packets without ACKs (DoS attempt)
    SynFlood,
    /// A single source scanning many ports on a single host (Reconnaissance)
    VerticalPortScan,
    /// A single source scanning many hosts on a fixed port (Subnet Sweep)
    HorizontalSweep,
}

/// Structured security alert generated by FastFlow anomaly analysis engine.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AnomalyAlert {
    pub anomaly_type: AnomalyType,
    pub source_ip: IpAddr,
    pub target_ip: Option<IpAddr>,
    pub port: Option<u16>,
    pub details: String,
}

/// Time-bucketed throughput metric.
#[derive(Debug, Clone, PartialEq)]
pub struct TimeBucket {
    pub start_time: f64,
    pub end_time: f64,
    pub packet_count: u64,
    pub byte_count: u64,
    pub bandwidth_bps: f64,
}

/// High-throughput telemetry and traffic aggregator.
#[derive(Debug, Default)]
pub struct TrafficAggregator {
    flows: HashMap<FlowKey, FlowMetrics>,
    ip_packet_counts: HashMap<IpAddr, u64>,
    ip_byte_counts: HashMap<IpAddr, u64>,
    protocol_counts: HashMap<u8, u64>,
    port_counts: HashMap<u16, u64>,
    src_dst_ports: HashMap<(IpAddr, IpAddr), HashSet<u16>>,
    src_dst_ips_by_port: HashMap<(IpAddr, u16), HashSet<IpAddr>>,
    packet_timeline: Vec<(f64, u32)>,
    total_packets: u64,
    total_bytes: u64,
}

impl TrafficAggregator {
    pub fn new() -> Self {
        Self::default()
    }

    /// Ingests a single packet record into all aggregate metrics.
    pub fn ingest(&mut self, record: &PacketRecord) {
        self.total_packets += 1;
        self.total_bytes += record.captured_len as u64;

        let ts = (record.timestamp_secs as f64) + ((record.timestamp_sub as f64) / 1_000_000.0);
        self.packet_timeline.push((ts, record.captured_len));

        if let Some(src) = record.src_ip {
            *self.ip_packet_counts.entry(src).or_insert(0) += 1;
            *self.ip_byte_counts.entry(src).or_insert(0) += record.captured_len as u64;
        }

        if let Some(proto) = record.protocol {
            *self.protocol_counts.entry(proto).or_insert(0) += 1;
        }

        if let Some(dst_port) = record.dst_port {
            *self.port_counts.entry(dst_port).or_insert(0) += 1;
        }

        if let (Some(src_ip), Some(dst_ip)) = (record.src_ip, record.dst_ip) {
            if let Some(port) = record.dst_port {
                self.src_dst_ports
                    .entry((src_ip, dst_ip))
                    .or_default()
                    .insert(port);

                self.src_dst_ips_by_port
                    .entry((src_ip, port))
                    .or_default()
                    .insert(dst_ip);
            }
        }

        if let (Some(src_ip), Some(dst_ip), Some(src_port), Some(dst_port), Some(protocol)) = (
            record.src_ip,
            record.dst_ip,
            record.src_port,
            record.dst_port,
            record.protocol,
        ) {
            let key = FlowKey {
                src_ip,
                dst_ip,
                src_port,
                dst_port,
                protocol,
            }
            .canonical();

            self.flows.entry(key).or_default().update(record);
        }
    }

    /// Evaluates traffic patterns to detect security anomalies (SYN floods, port scans).
    pub fn detect_anomalies(&self) -> Vec<AnomalyAlert> {
        let mut alerts = Vec::new();

        // 1. Detect SYN floods (high SYN ratio with low or zero completion)
        for (flow_key, metrics) in &self.flows {
            if metrics.syn_count >= 10
                && metrics.syn_count > (metrics.fin_count + metrics.rst_count) * 4
            {
                alerts.push(AnomalyAlert {
                    anomaly_type: AnomalyType::SynFlood,
                    source_ip: flow_key.src_ip,
                    target_ip: Some(flow_key.dst_ip),
                    port: Some(flow_key.dst_port),
                    details: format!(
                        "Potential SYN Flood: {} SYNs sent with only {} completions",
                        metrics.syn_count, metrics.fin_count
                    ),
                });
            }
        }

        // 2. Detect Vertical Port Scans (single IP probing >= 10 ports on a single host)
        for (&(src_ip, dst_ip), ports) in &self.src_dst_ports {
            if ports.len() >= 8 {
                alerts.push(AnomalyAlert {
                    anomaly_type: AnomalyType::VerticalPortScan,
                    source_ip: src_ip,
                    target_ip: Some(dst_ip),
                    port: None,
                    details: format!(
                        "Vertical Port Scan: Host probed {} distinct destination ports on target",
                        ports.len()
                    ),
                });
            }
        }

        // 3. Detect Horizontal Sweeps (single IP probing >= 8 distinct hosts on same port)
        for (&(src_ip, port), targets) in &self.src_dst_ips_by_port {
            if targets.len() >= 8 {
                alerts.push(AnomalyAlert {
                    anomaly_type: AnomalyType::HorizontalSweep,
                    source_ip: src_ip,
                    target_ip: None,
                    port: Some(port),
                    details: format!(
                        "Horizontal Subnet Sweep: Host probed port {} across {} distinct target IPs",
                        port,
                        targets.len()
                    ),
                });
            }
        }

        alerts
    }

    /// Computes time-bucketed bandwidth and throughput over specified interval (e.g. 1.0 second).
    pub fn bandwidth_timeline(&self, bucket_secs: f64) -> Vec<TimeBucket> {
        if self.packet_timeline.is_empty() || bucket_secs <= 0.0 {
            return Vec::new();
        }

        let min_ts = self
            .packet_timeline
            .iter()
            .map(|&(t, _)| t)
            .fold(f64::INFINITY, f64::min);
        let max_ts = self
            .packet_timeline
            .iter()
            .map(|&(t, _)| t)
            .fold(f64::NEG_INFINITY, f64::max);

        let duration = max_ts - min_ts;
        let num_buckets = ((duration / bucket_secs).ceil() as usize).max(1);
        let mut buckets = Vec::with_capacity(num_buckets);

        for i in 0..num_buckets {
            let start = min_ts + (i as f64 * bucket_secs);
            let end = start + bucket_secs;
            buckets.push(TimeBucket {
                start_time: start,
                end_time: end,
                packet_count: 0,
                byte_count: 0,
                bandwidth_bps: 0.0,
            });
        }

        for &(ts, len) in &self.packet_timeline {
            let idx = ((ts - min_ts) / bucket_secs).floor() as usize;
            if idx < buckets.len() {
                buckets[idx].packet_count += 1;
                buckets[idx].byte_count += len as u64;
            }
        }

        for b in &mut buckets {
            b.bandwidth_bps = (b.byte_count as f64 * 8.0) / bucket_secs;
        }

        buckets
    }

    /// Batch ingest an entire slice of packet records.
    pub fn ingest_batch(&mut self, records: &[PacketRecord]) {
        for record in records {
            self.ingest(record);
        }
    }

    /// Returns top talkers ranked by total transmitted packets.
    pub fn top_talkers_by_packets(&self, limit: usize) -> Vec<(IpAddr, u64)> {
        let mut sorted: Vec<(IpAddr, u64)> = self
            .ip_packet_counts
            .iter()
            .map(|(&ip, &c)| (ip, c))
            .collect();
        sorted.sort_unstable_by_key(|a| std::cmp::Reverse(a.1));
        sorted.truncate(limit);
        sorted
    }

    /// Returns top talkers ranked by total transmitted bytes.
    pub fn top_talkers_by_bytes(&self, limit: usize) -> Vec<(IpAddr, u64)> {
        let mut sorted: Vec<(IpAddr, u64)> = self
            .ip_byte_counts
            .iter()
            .map(|(&ip, &c)| (ip, c))
            .collect();
        sorted.sort_unstable_by_key(|a| std::cmp::Reverse(a.1));
        sorted.truncate(limit);
        sorted
    }

    /// Returns the top canonical flow conversations ranked by volume.
    pub fn top_flows(&self, limit: usize) -> Vec<(FlowKey, FlowMetrics)> {
        let mut sorted: Vec<(FlowKey, FlowMetrics)> =
            self.flows.iter().map(|(&k, m)| (k, m.clone())).collect();
        sorted.sort_unstable_by_key(|a| std::cmp::Reverse(a.1.byte_count));
        sorted.truncate(limit);
        sorted
    }

    /// Returns protocol distribution (protocol number -> count).
    pub fn protocol_distribution(&self) -> &HashMap<u8, u64> {
        &self.protocol_counts
    }

    /// Returns port distribution (destination port -> count).
    pub fn port_distribution(&self) -> &HashMap<u16, u64> {
        &self.port_counts
    }

    pub fn total_packets(&self) -> u64 {
        self.total_packets
    }

    pub fn total_bytes(&self) -> u64 {
        self.total_bytes
    }
}
